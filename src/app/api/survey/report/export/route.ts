import { NextResponse } from 'next/server'
import ExcelJS from 'exceljs'
import { getSessionUser } from '@/lib/auth'
import { buildSurveyReport } from '@/lib/survey'
import { fmtDateTime, istToday } from '@/lib/dates'

export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'

const BRAND = 'FF2E4566'
const BRAND_SOFT = 'FFEEF2F7'
const BORDER_COLOR = 'FFD9E1EC'
const MUTED = 'FF64748B'

function styleHeaderRow(row: ExcelJS.Row) {
  row.font = { bold: true, color: { argb: BRAND } }
  row.alignment = { vertical: 'middle', wrapText: false }
  row.eachCell((cell) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_SOFT } }
    cell.border = { bottom: { style: 'thin', color: { argb: BORDER_COLOR } } }
  })
}

/**
 * GET /api/survey/report/export — ADMIN only.
 * Excel workbook of the employee feedback survey.
 * Sheets: Summary · Question Scores · By Process · Responses · Pending.
 */
export async function GET() {
  const session = await getSessionUser()
  if (!session) return NextResponse.json({ error: 'Not authenticated' }, { status: 401 })
  if (session.role !== 'ADMIN') return NextResponse.json({ error: 'Admins only' }, { status: 403 })

  const report = await buildSurveyReport()
  const { kpis, questions, byProcess, responses, pending } = report

  const wb = new ExcelJS.Workbook()
  wb.creator = 'Tasknet'
  wb.created = new Date()
  wb.title = 'Tasknet — Employee Feedback Survey'

  const kpiRows: [string, string | number][] = [
    ['Eligible employees', kpis.eligibleEmployees],
    ['Responses received', kpis.submitted],
    ['Pending responses', kpis.pending],
    ['Response rate', `${kpis.responseRate}%`],
    ['Average overall satisfaction', `${kpis.avgOverall} / 5`],
    ['Average ease of use', `${kpis.avgEaseOfUse} / 5`],
    ['Average staying on top of tasks', `${kpis.avgTaskClarity} / 5`],
    ['Average notification usefulness', `${kpis.avgNotifications} / 5`],
    ['Average recommendation', `${kpis.avgRecommend} / 5`],
    ['Would recommend (rated 4–5)', `${kpis.recommendRate}%`],
    ['Satisfied employees (overall 4–5)', `${kpis.satisfiedEmployees} (${kpis.satisfiedRate}%)`],
    ['Responses with written comments', kpis.commentCount],
  ]

  // ── Sheet 1: Summary ────────────────────────────────────────────
  const wsSummary = wb.addWorksheet('Summary')
  wsSummary.columns = [{ width: 40 }, { width: 28 }]
  wsSummary.addRow(['Tasknet — Employee Feedback Survey'])
  wsSummary.mergeCells('A1:B1')
  wsSummary.getCell('A1').font = { bold: true, size: 15, color: { argb: BRAND } }
  wsSummary.addRow([`Generated by ${session.name} (${session.employeeCode})`])
  wsSummary.addRow([`Generated on ${fmtDateTime(new Date())} IST`])
  wsSummary.addRow(['One-time survey · employees only · ADMIN accounts are exempt'])
  wsSummary.addRow([])
  wsSummary.addRow(['Key metrics'])
  wsSummary.getCell(`A${wsSummary.rowCount}`).font = { bold: true, color: { argb: BRAND } }
  styleHeaderRow(wsSummary.addRow(['Metric', 'Value']))
  for (const [k, v] of kpiRows) wsSummary.addRow([k, v])
  wsSummary.addRow([])
  wsSummary.addRow(['Definitions'])
  wsSummary.getCell(`A${wsSummary.rowCount}`).font = { bold: true, color: { argb: BRAND } }
  wsSummary.addRow(['Eligible employees', 'Active employees (ADMIN accounts are excluded)']).getCell(2).font = { color: { argb: MUTED } }
  wsSummary.addRow(['Ratings', 'Every rating is on a 1–5 scale; “positive” means a rating of 4 or 5']).getCell(2).font = { color: { argb: MUTED } }
  wsSummary.addRow(['One submission', 'Each employee can submit the survey exactly once']).getCell(2).font = { color: { argb: MUTED } }

  // ── Sheet 2: Question Scores ────────────────────────────────────
  const wsQuestions = wb.addWorksheet('Question Scores', { views: [{ state: 'frozen', ySplit: 1 }] })
  styleHeaderRow(
    wsQuestions.addRow([
      'Question',
      'Average (/5)',
      'Positive (4–5) %',
      'Score 1',
      'Score 2',
      'Score 3',
      'Score 4',
      'Score 5',
    ])
  )
  for (const q of questions) {
    wsQuestions.addRow([
      q.shortLabel,
      q.average,
      q.positiveRate,
      ...q.distribution.map((d) => d.count),
    ])
  }
  wsQuestions.columns = [
    { width: 32 },
    { width: 14 },
    { width: 17 },
    { width: 10 },
    { width: 10 },
    { width: 10 },
    { width: 10 },
    { width: 10 },
  ]

  // ── Sheet 3: By Process ─────────────────────────────────────────
  const wsProc = wb.addWorksheet('By Process', { views: [{ state: 'frozen', ySplit: 1 }] })
  styleHeaderRow(
    wsProc.addRow([
      'Process',
      'Employees',
      'Responses',
      'Response rate %',
      'Avg overall (/5)',
      'Avg recommendation (/5)',
      'Would recommend %',
    ])
  )
  for (const p of byProcess) {
    wsProc.addRow([
      p.process,
      p.employees,
      p.submitted,
      p.responseRate,
      p.avgOverall,
      p.avgRecommend,
      p.recommendRate,
    ])
  }
  wsProc.columns = [
    { width: 22 },
    { width: 12 },
    { width: 12 },
    { width: 16 },
    { width: 17 },
    { width: 22 },
    { width: 19 },
  ]
  wsProc.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, byProcess.length + 1), column: 7 } }

  // ── Sheet 4: Responses ──────────────────────────────────────────
  const wsResponses = wb.addWorksheet('Responses', { views: [{ state: 'frozen', ySplit: 1 }] })
  styleHeaderRow(
    wsResponses.addRow([
      'Employee Code',
      'Employee',
      'Process',
      'Designation',
      'Submitted on',
      'Overall',
      'Ease of use',
      'Staying on top',
      'Notifications',
      'Would recommend',
      'Average',
      'What they like most',
      'What to improve',
      'Anything else',
    ])
  )
  for (const r of responses) {
    const row = wsResponses.addRow([
      r.employeeCode,
      r.name,
      r.process,
      r.designation,
      fmtDateTime(r.createdAt),
      r.overall,
      r.easeOfUse,
      r.taskClarity,
      r.notifications,
      r.recommend,
      r.average,
      r.likedMost ?? '',
      r.improvements ?? '',
      r.comments ?? '',
    ])
    for (const col of [12, 13, 14]) row.getCell(col).alignment = { wrapText: true, vertical: 'top' }
  }
  wsResponses.columns = [
    { width: 15 },
    { width: 22 },
    { width: 16 },
    { width: 18 },
    { width: 20 },
    { width: 9 },
    { width: 11 },
    { width: 12 },
    { width: 12 },
    { width: 15 },
    { width: 9 },
    { width: 38 },
    { width: 38 },
    { width: 38 },
  ]
  wsResponses.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: Math.max(1, responses.length + 1), column: 14 },
  }

  // ── Sheet 5: Pending ────────────────────────────────────────────
  const wsPending = wb.addWorksheet('Pending', { views: [{ state: 'frozen', ySplit: 1 }] })
  styleHeaderRow(wsPending.addRow(['Employee Code', 'Employee', 'Process', 'Designation']))
  for (const p of pending) wsPending.addRow([p.employeeCode, p.name, p.process, p.designation])
  wsPending.columns = [{ width: 15 }, { width: 24 }, { width: 18 }, { width: 22 }]
  wsPending.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: Math.max(1, pending.length + 1), column: 4 },
  }

  const arrayBuffer = await wb.xlsx.writeBuffer()
  const body = new Uint8Array(arrayBuffer as unknown as ArrayBuffer)
  const filename = `Tasknet-Feedback-${istToday()}.xlsx`
  return new NextResponse(body, {
    headers: {
      'Content-Type': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      'Content-Disposition': `attachment; filename="${filename}"`,
      'Cache-Control': 'no-store',
    },
  })
}
