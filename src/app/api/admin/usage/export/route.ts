import { NextResponse } from 'next/server'
import ExcelJS from 'exceljs'
import { getSessionUser } from '@/lib/auth'
import { buildUsageReport } from '@/lib/usage-report'
import { buildUsageChartImages } from '@/lib/excel-charts'
import { fmtDateTime, istToday } from '@/lib/dates'
import type { NextRequest } from 'next/server'

export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'

const BRAND = 'FF2E4566'
const BRAND_SOFT = 'FFEEF2F7'
const BORDER_COLOR = 'FFD9E1EC'
const MUTED = 'FF64748B'

function styleHeaderRow(row: ExcelJS.Row) {
  row.font = { bold: true, color: { argb: BRAND } }
  row.alignment = { vertical: 'middle', wrapText: false }
  row.eachCell((cell) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_SOFT } }
    cell.border = { bottom: { style: 'thin', color: { argb: BORDER_COLOR } } }
  })
}

/**
 * GET /api/admin/usage/export — ADMIN only. Excel workbook of the Tool
 * Adoption & Usage report, honoring the same ?days window as /api/admin/usage.
 * Sheets: Summary · Snapshots (charts) · Adoption Trend · Feature Usage ·
 * Usage by Process · Most Active Employees · Employees.
 */
export async function GET(req: NextRequest) {
  const session = await getSessionUser()
  if (!session) return NextResponse.json({ error: 'Not authenticated' }, { status: 401 })
  if (!session.permissions.exportData) return NextResponse.json({ error: 'Admins only' }, { status: 403 })

  const { report, employees } = await buildUsageReport(req.nextUrl.searchParams.get('days'))
  const { days, kpis, onboarding, adoptionTrend, featureUsage, byProcess, topEmployees } = report

  const wb = new ExcelJS.Workbook()
  wb.creator = 'Tasknet'
  wb.created = new Date()
  wb.title = 'Tasknet — Tool Adoption & Usage Report'

  const kpiRows: [string, string | number][] = [
    ['Employees', kpis.totalEmployees],
    ['Active employees', kpis.activeEmployees],
    ['Adopted employees', `${kpis.adopted} (${kpis.adoptedRate}%)`],
    [`Active in last ${days} days`, `${kpis.activeUsers} (${kpis.engagementRate}%)`],
    ['New employees this period', kpis.newThisPeriod],
    ['Tasks created this period', kpis.tasksCreated],
    ['Tasks completed this period', kpis.tasksCompleted],
    ['Passwords set (signed in once)', kpis.passwordSet],
    ['Android app users', `${kpis.appUsers} (${kpis.appRate}%)`],
    ['Web push enabled', `${kpis.pushUsers} (${kpis.pushRate}%)`],
  ]
  const funnel: [string, number][] = [
    ['Employees', onboarding.employees],
    ['Password set (signed in once)', onboarding.passwordSet],
    ['Android app installed', onboarding.appInstalled],
    ['Active this period', onboarding.active],
  ]
  const funnelPct = (v: number) => (onboarding.employees > 0 ? Math.round((v / onboarding.employees) * 100) : 0)

  // ── Sheet 1: Summary ────────────────────────────────────────────
  const wsSummary = wb.addWorksheet('Summary')
  wsSummary.columns = [{ width: 36 }, { width: 32 }, { width: 14 }]
  wsSummary.addRow(['Tasknet — Tool Adoption & Usage Report'])
  wsSummary.mergeCells('A1:C1')
  wsSummary.getCell('A1').font = { bold: true, size: 15, color: { argb: BRAND } }
  wsSummary.addRow([`Generated by ${session.name} (${session.employeeCode})`])
  wsSummary.addRow([`Generated on ${fmtDateTime(new Date())} IST`])
  wsSummary.addRow([`Period: last ${days} days`])
  wsSummary.addRow([])
  wsSummary.addRow(['Key metrics'])
  wsSummary.getCell(`A${wsSummary.rowCount}`).font = { bold: true, color: { argb: BRAND } }
  styleHeaderRow(wsSummary.addRow(['Metric', 'Value']))
  for (const [k, v] of kpiRows) wsSummary.addRow([k, v])
  wsSummary.addRow([])
  wsSummary.addRow(['Onboarding funnel'])
  wsSummary.getCell(`A${wsSummary.rowCount}`).font = { bold: true, color: { argb: BRAND } }
  styleHeaderRow(wsSummary.addRow(['Stage', 'Employees', '% of total']))
  for (const [label, value] of funnel) wsSummary.addRow([label, value, funnelPct(value)])
  wsSummary.addRow([])
  wsSummary.addRow(['Definitions'])
  wsSummary.getCell(`A${wsSummary.rowCount}`).font = { bold: true, color: { argb: BRAND } }
  wsSummary.addRow(['Adopted', 'Employees who have recorded at least one action']).getCell(2).font = { color: { argb: MUTED } }
  wsSummary.addRow([`Active (${days}d)`, 'Employees with any action in the selected window']).getCell(2).font = { color: { argb: MUTED } }

  // ── Sheet 2: Snapshots (KPI + charts) ───────────────────────────
  const wsSnap = wb.addWorksheet('Snapshots')
  wsSnap.columns = [{ width: 2 }, { width: 36 }, { width: 16 }, { width: 14 }, { width: 14 }, { width: 14 }]
  wsSnap.getCell('B2').value = 'Tasknet — Usage Snapshots'
  wsSnap.getCell('B2').font = { bold: true, size: 16, color: { argb: BRAND } }
  wsSnap.getCell('B3').value = `Generated by ${session.name} (${session.employeeCode}) · ${fmtDateTime(new Date())} IST`
  wsSnap.getCell('B3').font = { size: 10, color: { argb: MUTED } }
  wsSnap.getCell('B4').value = `Period: last ${days} days · ${kpis.activeEmployees} active employee${kpis.activeEmployees === 1 ? '' : 's'}`
  wsSnap.getCell('B4').font = { size: 10, color: { argb: MUTED } }
  styleHeaderRow(wsSnap.getRow(6))
  wsSnap.getRow(6).getCell(2).value = 'Key metrics'
  wsSnap.getRow(6).getCell(3).value = 'Value'
  for (const [k, v] of kpiRows) {
    const r = wsSnap.addRow(['', k, v])
    r.getCell(2).font = { size: 10, color: { argb: 'FF475569' } }
    r.getCell(3).font = { size: 10, bold: true, color: { argb: BRAND } }
  }

  let chartCount = 0
  try {
    const images = await buildUsageChartImages({ adoptionTrend, featureUsage, byProcess })
    chartCount = images.length
    let anchorRow = wsSnap.rowCount + 3
    for (const img of images) {
      const imageId = wb.addImage({ buffer: img.buffer as unknown as ExcelJS.Buffer, extension: 'png' })
      wsSnap.addImage(imageId, {
        tl: { col: 1.15, row: anchorRow },
        ext: { width: img.width, height: img.height },
        editAs: 'oneCell',
      })
      anchorRow += Math.ceil(img.height / 20) + 2
    }
  } catch (e) {
    console.error('usage chart image build error', e)
    wsSnap.getCell('B20').value = 'Charts could not be generated for this export.'
  }

  // ── Sheet 3: Adoption Trend ─────────────────────────────────────
  const wsTrend = wb.addWorksheet('Adoption Trend', { views: [{ state: 'frozen', ySplit: 1 }] })
  styleHeaderRow(wsTrend.addRow(['Month', 'New sign-ups', 'Active users']))
  for (const m of adoptionTrend) wsTrend.addRow([m.label, m.newUsers, m.activeUsers])
  wsTrend.columns = [{ width: 16 }, { width: 16 }, { width: 14 }]

  // ── Sheet 4: Feature Usage ──────────────────────────────────────
  const wsFeat = wb.addWorksheet('Feature Usage', { views: [{ state: 'frozen', ySplit: 1 }] })
  styleHeaderRow(wsFeat.addRow(['Action', 'Actions logged', '% of actions']))
  const totalActions = featureUsage.reduce((s, f) => s + f.count, 0)
  for (const f of featureUsage) {
    wsFeat.addRow([f.label, f.count, totalActions > 0 ? Math.round((f.count / totalActions) * 100) : 0])
  }
  wsFeat.columns = [{ width: 26 }, { width: 16 }, { width: 14 }]

  // ── Sheet 5: Usage by Process ───────────────────────────────────
  const wsProc = wb.addWorksheet('Usage by Process', { views: [{ state: 'frozen', ySplit: 1 }] })
  styleHeaderRow(wsProc.addRow(['Process', 'Employees', 'Adopted', 'Active', 'Tasks created', 'Actions', 'Adoption %']))
  for (const p of byProcess) {
    wsProc.addRow([
      p.process,
      p.employees,
      p.adopted,
      p.active,
      p.tasksCreated,
      p.activities,
      p.employees > 0 ? Math.round((p.adopted / p.employees) * 100) : 0,
    ])
  }
  wsProc.columns = [{ width: 18 }, { width: 12 }, { width: 10 }, { width: 10 }, { width: 14 }, { width: 10 }, { width: 12 }]
  wsProc.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, byProcess.length + 1), column: 7 } }

  // ── Sheet 6: Most Active Employees ──────────────────────────────
  const wsTop = wb.addWorksheet('Most Active Employees', { views: [{ state: 'frozen', ySplit: 1 }] })
  styleHeaderRow(wsTop.addRow(['#', 'Employee', 'Employee Code', 'Process', 'Actions', 'Tasks created']))
  topEmployees.forEach((e, i) => wsTop.addRow([i + 1, e.name, e.employeeCode, e.process, e.activities, e.tasksCreated]))
  wsTop.columns = [{ width: 6 }, { width: 22 }, { width: 15 }, { width: 16 }, { width: 12 }, { width: 14 }]

  // ── Sheet 6: Employee detail ────────────────────────────────────
  const wsEmp = wb.addWorksheet('Employees', { views: [{ state: 'frozen', ySplit: 1 }] })
  styleHeaderRow(
    wsEmp.addRow([
      'Employee Code', 'Employee', 'Process', 'Status',
      'Adopted', `Active (${days}d)`, 'Actions', 'Tasks created',
      'Password set', 'Android app', 'Web push',
    ])
  )
  for (const e of employees) {
    wsEmp.addRow([
      e.employeeCode, e.name, e.process, e.isActive ? 'Active' : 'Inactive',
      e.adopted ? 'Yes' : 'No', e.active ? 'Yes' : 'No', e.actions, e.tasksCreated,
      e.passwordSet ? 'Yes' : 'No', e.app ? 'Yes' : 'No', e.push ? 'Yes' : 'No',
    ])
  }
  wsEmp.columns = [{ width: 15 }, { width: 22 }, { width: 16 }, { width: 10 }, { width: 10 }, { width: 12 }, { width: 10 }, { width: 14 }, { width: 14 }, { width: 13 }, { width: 11 }]
  wsEmp.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, employees.length + 1), column: 11 } }

  const arrayBuffer = await wb.xlsx.writeBuffer()
  const body = new Uint8Array(arrayBuffer as unknown as ArrayBuffer)
  const filename = `Tasknet-Usage-${istToday()}.xlsx`
  return new NextResponse(body, {
    headers: {
      'Content-Type': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      'Content-Disposition': `attachment; filename="${filename}"`,
      'Cache-Control': 'no-store',
      'X-Chart-Count': String(chartCount),
    },
  })
}
