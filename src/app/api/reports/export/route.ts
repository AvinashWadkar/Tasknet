export const runtime = 'nodejs'

const BRAND = 'FF2E4566'
const BRAND_SOFT = 'FFEEF2F7'
const BORDER_COLOR = 'FFD9E1EC'

function styleHeaderRow(row: ExcelJS.Row) {
  row.font = { bold: true, color: { argb: BRAND } }
  row.alignment = { vertical: 'middle', wrapText: false }
  row.eachCell((cell) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_SOFT } }
    cell.border = { bottom: { style: 'thin', color: { argb: BORDER_COLOR } } }
  })
}

function weekdayName(iso: string): string {
  return ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'][Number(iso) - 1] ?? ''
}

function recurrenceLabel(t: {
  recurring: boolean
  recurFreq: string | null
  recurInterval: number | null
  recurWeekdays: string | null
  recurMonthDay: number | null
}): string {
  if (!t.recurring) return 'One-off'
  const n = t.recurInterval ?? 1
  if (t.recurFreq === 'DAILY') return n === 1 ? 'Daily' : `Every ${n} days`
  if (t.recurFreq === 'WEEKLY') {
    const base = n === 1 ? 'Weekly' : `Every ${n} weeks`
    const days = (t.recurWeekdays || '')
      .split(',')
      .map((d) => d.trim())
      .filter(Boolean)
      .map(weekdayName)
      .filter(Boolean)
    return days.length ? `${base} on ${days.join(', ')}` : base
  }
  if (t.recurFreq === 'MONTHLY') {
    const base = n === 1 ? 'Monthly' : `Every ${n} months`
    return t.recurMonthDay ? `${base} on day ${t.recurMonthDay}` : base
  }
  return 'Recurring'
}

/**
 * GET /api/reports/export — Excel workbook for the viewer's scope, honoring
 * the same filters as /api/reports.
 * Sheets: Summary · Snapshots (charts) · Employee Performance · Task Details · RAW.
 */
export async function GET(req: Request) {
  const session = await getSessionUser()
  if (!session) return NextResponse.json({ error: 'Not authenticated' }, { status: 401 })

  const scope = await getReportScope(session)
  if (!scope || scope.users.length === 0) {
    return NextResponse.json({ error: 'You do not have any team members reporting to you' }, { status: 403 })
  }

  const filters = parseFilterParams(new URL(req.url).searchParams)
  const allRows = await loadReportRows(scope.users)
  const report = buildReport(scope.users, allRows, filters, session)
  const { kpis, byEmployee, statusMix, monthly, byProcess, byDesignation, rows, options } = report

  const labelFor = (opts: { value: string; label: string }[], values: string[]) => {
    if (!values.length) return 'All'
    if (values.includes('__NONE__')) return 'None'
    return values.map((v) => opts.find((o) => o.value === v)?.label ?? v).join(', ')
  }
  const plainList = (values: string[]) => {
    if (!values.length) return 'All'
    if (values.includes('__NONE__')) return 'None'
    return values.join(', ')
  }
  const filtersApplied: [string, string][] = [
    ['Month (due date)', labelFor(options.months, filters.months)],
    ['Process', plainList(filters.processes)],
    ['Designation', plainList(filters.designations)],
    ['L1 Manager', labelFor(options.managers, filters.managerIds)],
    ['Employee', labelFor(options.employees, filters.userIds)],
  ]

  const wb = new ExcelJS.Workbook()
  wb.creator = 'Tasknet'
  wb.created = new Date()

  // ── Sheet 1: Summary ────────────────────────────────────────────
  const wsSummary = wb.addWorksheet('Summary')
  wsSummary.columns = [{ width: 32 }, { width: 52 }]
  wsSummary.addRow(['Tasknet — Team Performance Report'])
  wsSummary.mergeCells('A1:B1')
  wsSummary.getCell('A1').font = { bold: true, size: 15, color: { argb: BRAND } }
  wsSummary.addRow([`Generated by ${session.name} (${session.employeeCode})`])
  wsSummary.addRow([`Generated on ${fmtDateTime(new Date())} IST`])
  wsSummary.addRow([`Scope: ${scope.scope === 'org' ? 'Whole organization' : 'Your downline'}`])
  wsSummary.addRow([])
  wsSummary.addRow(['Filters applied'])
  wsSummary.getCell(`A${wsSummary.rowCount}`).font = { bold: true, color: { argb: BRAND } }
  for (const [k, v] of filtersApplied) wsSummary.addRow([k, v])
  wsSummary.addRow([])
  const summaryKpiHeader = wsSummary.addRow(['Key metrics', 'Value'])
  styleHeaderRow(summaryKpiHeader)
  const kpiRows: [string, number][] = [
    ['Employees in scope', kpis.employees],
    ['Total assignments', kpis.total],
    ['Completed', kpis.completed],
    ['Completed on time', kpis.onTime],
    ['Completed late', kpis.late],
    ['Pending (on track)', kpis.pending],
    ['In progress (on track)', kpis.inProgress],
    ['Overdue (open, past due)', kpis.overdue],
    ['Aborted', kpis.aborted],
    ['Completion rate %', kpis.completionRate],
    ['On-time delivery rate %', kpis.onTimeRate],
  ]
  for (const [k, v] of kpiRows) wsSummary.addRow([k, v])

  // ── Sheet 2: Snapshots (KPI + charts) ───────────────────────────
  const wsSnap = wb.addWorksheet('Snapshots')
  wsSnap.columns = [
    { width: 2 }, { width: 34 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 },
  ]
  wsSnap.getCell('B2').value = 'Tasknet — Report Snapshots'
  wsSnap.getCell('B2').font = { bold: true, size: 16, color: { argb: BRAND } }
  wsSnap.getCell('B3').value = `Generated by ${session.name} (${session.employeeCode}) · ${fmtDateTime(new Date())} IST`
  wsSnap.getCell('B3').font = { size: 10, color: { argb: 'FF64748B' } }
  wsSnap.getCell('B4').value = `Scope: ${scope.scope === 'org' ? 'Whole organization' : 'Your downline'} · ${kpis.employees} employee${kpis.employees === 1 ? '' : 's'}`
  wsSnap.getCell('B4').font = { size: 10, color: { argb: 'FF64748B' } }
  wsSnap.getCell('B5').value = `Filters: ${filtersApplied.map(([k, v]) => `${k}: ${v}`).join('  |  ')}`
  wsSnap.getCell('B5').font = { size: 9, color: { argb: 'FF94A3B8' } }
  const snapHeader = wsSnap.getRow(7)
  snapHeader.getCell(2).value = 'Key metrics'
  snapHeader.getCell(3).value = 'Value'
  styleHeaderRow(snapHeader)
  for (const [k, v] of kpiRows) {
    const r = wsSnap.addRow(['', k, v])
    r.getCell(2).font = { size: 10, color: { argb: 'FF475569' } }
    r.getCell(3).font = { size: 10, bold: true, color: { argb: BRAND } }
  }

  // Chart images (best effort — never fail the whole export over a chart)
  let chartCount = 0
  try {
    const images = await buildChartImages({ statusMix, monthly, byEmployee, byProcess, byDesignation })
    chartCount = images.length
    if (images.length === 0) {
      wsSnap.getCell('B20').value = 'No chart data available for the selected filters.'
    }
    let anchorRow = wsSnap.rowCount + 3
    for (const img of images) {
      const imageId = wb.addImage({ buffer: img.buffer as unknown as ExcelJS.Buffer, extension: 'png' })
      wsSnap.addImage(imageId, {
        tl: { col: 1.15, row: anchorRow },
        ext: { width: img.width, height: img.height },
        editAs: 'oneCell',
      })
      anchorRow += Math.ceil(img.height / 20) + 2
    }
  } catch (e) {
    console.error('chart image build error', e)
    wsSnap.getCell('B20').value = 'Charts could not be generated for this export.'
  }

  // ── Sheet 3: Employee Performance ───────────────────────────────
  const wsEmp = wb.addWorksheet('Employee Performance', { views: [{ state: 'frozen', ySplit: 1 }] })
  const empHeader = [
    'Employee Code', 'Employee', 'Process', 'Designation', 'L1 Manager',
    'Total', 'Completed', 'On-time', 'Late', 'Pending', 'In Progress',
    'Overdue', 'Aborted', 'Completion %', 'On-time %', 'Avg Delay (days)',
  ]
  styleHeaderRow(wsEmp.addRow(empHeader))
  for (const e of byEmployee) {
    wsEmp.addRow([
      e.employeeCode, e.name, e.process, e.designation, e.managerName ?? '—',
      e.total, e.completed, e.onTime, e.late, e.pending, e.inProgress,
      e.overdue, e.aborted, e.completionRate, e.onTimeRate, e.avgDelayDays,
    ])
  }
  wsEmp.columns = empHeader.map((_, i) => ({ width: [14, 20, 14, 18, 20, 8, 10, 9, 7, 9, 11, 9, 9, 13, 10, 15][i] }))
  wsEmp.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, byEmployee.length + 1), column: empHeader.length } }

  // ── Sheet 4: Task Details ───────────────────────────────────────
  const wsDetail = wb.addWorksheet('Task Details', { views: [{ state: 'frozen', ySplit: 1 }] })
  const detailHeader = [
    'Task', 'Employee', 'Employee Code', 'Process', 'Designation', 'L1 Manager',
    'Assigned By', 'Due Date (IST)', 'Completed On (IST)', 'Status', 'Task State',
    'Overdue', 'Delay (days)',
  ]
  styleHeaderRow(wsDetail.addRow(detailHeader))
  for (const r of rows) {
    wsDetail.addRow([
      r.title,
      r.userName,
      r.employeeCode,
      r.process,
      r.designation,
      r.managerName ?? '—',
      r.assignedBy,
      fmtDateTime(r.dueDate),
      r.completedAt ? fmtDateTime(r.completedAt) : '—',
      r.aborted ? 'Aborted' : r.status === 'PENDING' ? 'Pending' : r.status === 'IN_PROGRESS' ? 'In Progress' : 'Completed',
      r.aborted ? 'Aborted' : 'Active',
      r.overdue ? 'Yes' : 'No',
      r.delayDays > 0 ? r.delayDays : 0,
    ])
  }
  wsDetail.columns = detailHeader.map((_, i) => ({ width: [34, 18, 13, 13, 16, 18, 16, 22, 22, 12, 11, 9, 12][i] }))
  wsDetail.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, rows.length + 1), column: detailHeader.length } }

  // ── Sheet 5: RAW (complete task details) ────────────────────────
  const taskIds = [...new Set(rows.map((r) => r.taskId))]
  const tasks = taskIds.length
    ? await db.task.findMany({
        where: { id: { in: taskIds } },
        select: {
          id: true, title: true, description: true, dueDate: true, createdAt: true,
          status: true, abortedAt: true, abortReason: true,
          recurring: true, recurFreq: true, recurInterval: true, recurWeekdays: true, recurMonthDay: true,
          creator: { select: { name: true, employeeCode: true } },
          validator: { select: { name: true, employeeCode: true } },
          assignments: {
            select: {
              userId: true, status: true, completedAt: true, note: true,
              validationStatus: true, sentForValidationAt: true, validatedAt: true,
            },
          },
        },
      })
    : []
  const taskById = new Map(tasks.map((t) => [t.id, t]))
  const assignmentByKey = new Map<string, (typeof tasks)[number]['assignments'][number]>()
  for (const t of tasks) for (const a of t.assignments) assignmentByKey.set(`${t.id}::${a.userId}`, a)

  const wsRaw = wb.addWorksheet('RAW', { views: [{ state: 'frozen', ySplit: 1 }] })
  const rawHeader = [
    'Task ID', 'Task', 'Description', 'Assigned By', 'Assigned By Code',
    'Task Created (IST)', 'Due Date (IST)', 'Task State', 'Aborted On (IST)', 'Abort Reason',
    'Recurrence', 'Validator',
    'Employee', 'Employee Code', 'Process', 'Designation', 'L1 Manager',
    'Assignment Status', 'Completed On (IST)', 'Completion Note',
    'Validation', 'Sent For Validation (IST)', 'Validated On (IST)',
    'On Time', 'Overdue', 'Delay (days)',
  ]
  styleHeaderRow(wsRaw.addRow(rawHeader))
  for (const r of rows) {
    const t = taskById.get(r.taskId)
    const a = assignmentByKey.get(`${r.taskId}::${r.userId}`)
    const validation = a?.validationStatus === 'VALIDATED' ? 'Validated' : a?.validationStatus === 'PENDING' ? 'Pending review' : '—'
    wsRaw.addRow([
      r.taskId,
      r.title,
      t?.description ?? '',
      t?.creator.name ?? r.assignedBy,
      t?.creator.employeeCode ?? '',
      t ? fmtDateTime(t.createdAt) : fmtDateTime(r.createdAt),
      fmtDateTime(r.dueDate),
      r.aborted ? 'Aborted' : 'Active',
      t?.abortedAt ? fmtDateTime(t.abortedAt) : '—',
      t?.abortReason ?? '',
      t ? recurrenceLabel(t) : '—',
      t?.validator ? `${t.validator.name} (${t.validator.employeeCode})` : '—',
      r.userName,
      r.employeeCode,
      r.process,
      r.designation,
      r.managerName ?? '—',
      r.aborted ? 'Aborted' : r.status === 'PENDING' ? 'Pending' : r.status === 'IN_PROGRESS' ? 'In Progress' : 'Completed',
      a?.completedAt ? fmtDateTime(a.completedAt) : '—',
      a?.note ?? '',
      validation,
      a?.sentForValidationAt ? fmtDateTime(a.sentForValidationAt) : '—',
      a?.validatedAt ? fmtDateTime(a.validatedAt) : '—',
      r.status === 'COMPLETED' ? (r.onTime ? 'Yes' : 'No') : '—',
      r.overdue ? 'Yes' : 'No',
      r.delayDays > 0 ? r.delayDays : 0,
    ])
  }
  wsRaw.columns = rawHeader.map((_, i) => ({
    width: [24, 34, 40, 18, 15, 20, 20, 11, 20, 24, 22, 24, 18, 13, 13, 16, 18, 15, 20, 28, 13, 24, 22, 9, 9, 12][i],
  }))
  wsRaw.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, rows.length + 1), column: rawHeader.length } }

  const arrayBuffer = await wb.xlsx.writeBuffer()
  const body = new Uint8Array(arrayBuffer as unknown as ArrayBuffer)
  const filename = `Tasknet-Report-${istToday()}.xlsx`
  return new NextResponse(body, {
    headers: {
      'Content-Type': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      'Content-Disposition': `attachment; filename="${filename}"`,
      'Cache-Control': 'no-store',
      'X-Chart-Count': String(chartCount),
    },
  })
}
